// Аймгийн суманд багийн тоо харилцан адилгүй тул ерөнхий тоог ашиглана.
const DEFAULT_BAG_COUNT = 8;

// Сонгосон аймаг/сумаас хамаарч баг/хорооны жагсаалтыг үүсгэнэ.
// Улаанбаатарт "N-р хороо", бусад аймагт "N-р баг".
export function getSubDistricts(province: string, district: string): string[] {
  if (!province || !district) return [];
  const isUB = province === "Улаанбаатар";
  const unit = isUB ? "хороо" : "баг";
  const count = isUB ? (UB_KHOROO_COUNT[district] ?? 20) : DEFAULT_BAG_COUNT;
  return Array.from({ length: count }, (_, i) => `${i + 1}-р ${unit}`);
}
