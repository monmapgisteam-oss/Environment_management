// Writes src/routes/index.ts: one entry per src/routes/**/route.ts, with the
// URL Fastify serves it at ("[id]" folders become ":id" parameters). Static
// imports keep the bundle self-contained. Run after adding or removing a route.
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '../src/routes');

export function routeFiles(dir = root) {
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) return routeFiles(full);
    return entry.name === 'route.ts' ? [path.relative(root, full).split(path.sep).join('/')] : [];
  }).sort();
}

export function manifestSource(files = routeFiles()) {
  const lines = ['// Generated by `npm run routes` (scripts/generate-routes.mjs). Do not edit by hand.', ''];
  files.forEach((file, index) => lines.push(`import * as route${index} from './${file.replace(/\.ts$/, '')}';`));
  lines.push('', 'export const routes = [');
  files.forEach((file, index) => {
    const url = '/api/' + path.posix.dirname(file).replace(/\[([^\]]+)\]/g, ':$1');
    lines.push(`  { url: '${url}', module: route${index} },`);
  });
  lines.push('];', '');
  return lines.join('\n');
}

if (process.argv[1] === import.meta.filename) {
  fs.writeFileSync(path.join(root, 'index.ts'), manifestSource());
  console.log(`Wrote ${routeFiles().length} routes to src/routes/index.ts.`);
}
